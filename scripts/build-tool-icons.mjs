/**
 * Generates src/data/toolIcons.ts from the `simple-icons` package.
 *
 * Only the icons this site actually shows are emitted, so the runtime bundle
 * carries ~30 path strings instead of a 3,400-icon library. Re-run after adding
 * a tool or a project technology:
 *
 *     node scripts/build-tool-icons.mjs
 *
 * Licensing: simple-icons is CC0-1.0. The marks themselves remain the property
 * of their owners and are used here only to identify the tools actually used.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as si from 'simple-icons'

/** Names the data files actually render, so no unused path ships. */
const dataDir = fileURLToPath(new URL('../src/data/', import.meta.url))
const dataText = ['skills.ts', 'projects.ts', 'cyber.ts', 'ai.ts', 'fullstack.ts']
  .map((f) => readFileSync(dataDir + f, 'utf8'))
  .join('\n')
const referenced = new Set(
  [...dataText.matchAll(/'([A-Za-z0-9][^']{0,38})'/g)]
    .map((m) => m[1].toLowerCase().replace(/[^a-z0-9]/g, '')),
)

/** display name (as written in the data files) -> simple-icons slug */
const MAP = {
  // languages & runtimes
  Python: 'python',
  JavaScript: 'javascript',
  TypeScript: 'typescript',
  PHP: 'php',
  'HTML': 'html5',
  'CSS': 'css',
  C: 'c',
  'Node.js': 'nodedotjs',

  // frameworks & libraries
  React: 'react',
  Django: 'django',
  Flask: 'flask',
  FastAPI: 'fastapi',
  Streamlit: 'streamlit',
  PyQt6: 'qt',
  Vite: 'vite',
  'Tailwind CSS': 'tailwindcss',
  'Three.js': 'threedotjs',

  // data
  MySQL: 'mysql',
  MongoDB: 'mongodb',
  SQL: 'mysql',
  phpMyAdmin: 'phpmyadmin',

  // AI / ML
  PyTorch: 'pytorch',
  'Hugging Face': 'huggingface',
  'Ultralytics YOLO': 'ultralytics',
  YOLO: 'ultralytics',
  'YOLOv8n / YOLOv8x': 'ultralytics',
  OpenCV: 'opencv',
  spaCy: 'spacy',
  PaddleOCR: 'paddlepaddle',
  'Google Colab': 'googlecolab',

  // security
  'Burp Suite': 'burpsuite',
  'PortSwigger Academy': 'portswigger',
  PortSwigger: 'portswigger',
  Metasploit: 'metasploit',
  Wireshark: 'wireshark',
  'Kali Linux': 'kalilinux',
  Splunk: 'splunk',
  Qualys: 'qualys',
  VirusTotal: 'virustotal',
  OWASP: 'owasp',
  'OWASP Top 10': 'owasp',

  // platforms & tooling
  'Git / GitHub': 'github',
  Git: 'git',
  GitHub: 'github',
  'VS Code': 'vscodium',
  Docker: 'docker',
  Postman: 'postman',
  XAMPP: 'xampp',
  'VirtualBox / VMware': 'virtualbox',
  VirtualBox: 'virtualbox',
  ngrok: 'ngrok',
  ESP32: 'espressif',
}

const key = (name) => name.toLowerCase().replace(/[^a-z0-9]/g, '')
const camel = (slug) => 'si' + slug.charAt(0).toUpperCase() + slug.slice(1)

const found = {}
const missing = []
const unused = []

for (const [name, slug] of Object.entries(MAP)) {
  const icon = si[camel(slug)]
  if (!icon) {
    missing.push(`${name} (${slug})`)
    continue
  }
  // A few marks are enormous multi-path logos; a monogram costs nothing and
  // reads better at 16px than a 6 KB path.
  if (icon.path.length > 3600) {
    missing.push(`${name} (${slug}, ${icon.path.length}B — too heavy)`)
    continue
  }
  if (!referenced.has(key(name))) {
    unused.push(name)
    continue
  }
  found[key(name)] = { t: icon.title, d: icon.path }
}

const entries = Object.entries(found)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${JSON.stringify(k)}: { t: ${JSON.stringify(v.t)}, d: ${JSON.stringify(v.d)} },`)
  .join('\n')

const out = `/* GENERATED by scripts/build-tool-icons.mjs — do not edit by hand.
 *
 * Vendor marks from simple-icons (CC0-1.0), trimmed to the ${entries.split('\n').length} icons this
 * site actually renders. Each mark identifies a tool that is genuinely used;
 * trademarks remain with their owners.
 */

export interface ToolIconPath {
  /** Official mark title. */
  t: string
  /** 24×24 SVG path data. */
  d: string
}

export const TOOL_ICONS: Record<string, ToolIconPath> = {
${entries}
}

/** Normalises a display name to the icon key. */
export const iconKey = (name: string) => name.toLowerCase().replace(/[^a-z0-9]/g, '')

export function toolIcon(name: string): ToolIconPath | undefined {
  return TOOL_ICONS[iconKey(name)]
}
`

writeFileSync(new URL('../src/data/toolIcons.ts', import.meta.url), out)

console.log(`wrote src/data/toolIcons.ts — ${Object.keys(found).length} icons`)
if (missing.length) console.log(`no usable mark for: ${missing.join(', ')}`)
if (unused.length) console.log(`mapped but never rendered, so skipped: ${unused.join(', ')}`)
